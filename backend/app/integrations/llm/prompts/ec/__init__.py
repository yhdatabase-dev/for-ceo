from __future__ import annotations

import json
from pathlib import Path

_DATA_DIR = Path(__file__).resolve().parent / "_data"


def _load_json_prompts() -> dict[str, str]:
    """패키지 내부 json 에서 4종 프롬프트 로드. 파일 없으면 빈 dict."""
    fp = _DATA_DIR / "ec_prompts.json"
    if not fp.exists():
        return {}
    try:
        d = json.loads(fp.read_text(encoding="utf-8"))
    except Exception:
        return {}
    keys = ("STRUCTURE_PROMPT", "ANALYSIS_PROMPT", "GENERATION_PROMPT", "OCR_PROMPT")
    return {f"ec::{k}": str(d.get(k) or "") for k in keys}


